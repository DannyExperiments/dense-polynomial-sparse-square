"""Compare numeric Lean inputs to the JSON certificate and the period table."""

import argparse
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def render(proof):
    values = json.loads((proof / "certificate.json").read_text())
    if values["prime_count"] != 128 or values["degree_decimal_digits"] != 5798:
        raise ValueError("Unexpected certificate dimensions")
    if values["square_weight_over_sqrt_degree_strict_upper_bound"] != "501/1000":
        raise ValueError("Unexpected support ratio")
    with (proof / "proth-periods.csv").open() as f:
        primes = [row["prime"] for row in csv.DictReader(f)]
    fields = (("period", "period"), ("auxiliaryBase", "auxiliary_base"),
              ("repetitions", "repetitions"), ("degree", "degree"),
              ("weightUpper", "square_weight_upper_bound"))
    for number in primes + [values[key] for _, key in fields]:
        if not (number.isascii() and number.isdecimal()):
            raise ValueError("Expected an unsigned decimal integer")
    lines = ["-- Exact input literals from proof/certificate.json and proof/proth-periods.csv.",
             "-- Generated by check_inputs.py --write.", "namespace SparseSquare.Data", "",
             "def periods : List Nat := [", ",\n".join("  " + n for n in primes) + "]", ""]
    for name, field in fields:
        lines.extend([f"def {name} : Nat :=", "  " + values[field], ""])
    return "\n".join(lines + ["end SparseSquare.Data", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--proof-dir", type=Path, default=HERE.parent / "proof")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    target = HERE / "SparseSquare" / "Data.lean"
    expected = render(args.proof_dir)
    if args.write:
        target.write_text(expected)
    elif target.read_text() != expected:
        raise SystemExit("Lean inputs differ from proof certificate")
    print("Lean literals agree with all five certificate integers and the 128 period entries.")
